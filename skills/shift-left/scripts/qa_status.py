#!/usr/bin/env python3
"""Summarize test-index.csv state, hint the next stage, and generate RTM.

Usage:
  python3 qa_status.py <project>/test-index.csv          # status summary
  python3 qa_status.py rtm <project>/                     # generate RTM

The single state source is the CSV. The status subcommand reports counts by
stage_status and priority so the orchestrator can pick the next thin slice
without loading every artifact into context.

The rtm subcommand generates 07-rtm/rtm.md from test-index.csv, test-goals,
and checks every goal declared in 02-test-goals/test-goals.md has a scenario.
"""
import csv
import os
import re
import sys
from collections import Counter, defaultdict

STAGE_ORDER = ["goal", "plan", "scenario", "env-data", "case", "rtm"]


def status(path: str) -> int:
    try:
        with open(path, newline="", encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
    except FileNotFoundError:
        print(f"no csv at {path}: Stage 4 (test scenarios) seeds it; run stages 0-3 first")
        return 0

    if not rows:
        print("csv has header only — stage 4 (test scenarios) not yet seeded")
        return 0

    by_status = Counter(r.get("stage_status", "").strip() or "(blank)" for r in rows)
    by_priority = Counter(r.get("priority", "").strip() or "(none)" for r in rows)
    by_type = Counter(r.get("test_type", "").strip() or "(none)" for r in rows)

    print(f"scenarios/cases tracked: {len(rows)}")
    print("\nby stage_status:")
    for k in STAGE_ORDER + ["(blank)"]:
        v = by_status.get(k, 0)
        if v:
            print(f"  {k:<12} {v}")

    print("\nby priority:")
    for k, v in sorted(by_priority.items()):
        print(f"  {k:<8} {v}")

    print("\nby test_type:")
    for k, v in sorted(by_type.items()):
        print(f"  {k:<14} {v}")

    seeded = sum(by_status.values())
    cased = by_status.get("case", 0) + by_status.get("rtm", 0)
    if cased < seeded:
        pending = [r["scenario_id"] for r in rows
                   if r.get("stage_status", "").strip()
                   in ("goal", "plan", "scenario", "env-data")]
        p0 = [r["scenario_id"] for r in rows
              if r.get("stage_status", "").strip()
              in ("goal", "plan", "scenario", "env-data")
              and r.get("priority", "").strip() == "P0"]
        print(f"\nnext: stage 6 (test case) — {len(pending)} scenario(s) without a case")
        if p0:
            print(f"  P0 first: {', '.join(p0)}")
    else:
        print("\nall scenarios have cases — stage 6 complete for tracked rows")
        if by_status.get("rtm", 0) < seeded:
            print("next: stage 7 (rtm) — run `qa_status.py rtm <project>/`")
    return 0


def read_goal_ids(project_dir: str) -> list:
    """Goal IDs declared in 02-test-goals/test-goals.md as '## G<n> ...' headings."""
    path = os.path.join(project_dir, "02-test-goals", "test-goals.md")
    try:
        with open(path, encoding="utf-8") as f:
            return re.findall(r"^##\s+(G\d+)\b", f.read(), re.MULTILINE)
    except FileNotFoundError:
        return []


def generate_rtm(project_dir: str) -> int:
    csv_path = os.path.join(project_dir, "test-index.csv")
    try:
        with open(csv_path, newline="", encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
    except FileNotFoundError:
        print(f"error: no csv at {csv_path}", file=sys.stderr)
        return 1

    if not rows:
        print("csv has header only — nothing to trace", file=sys.stderr)
        return 1

    by_ac = defaultdict(list)
    for r in rows:
        ac = r.get("spec_ac", "").strip() or "(none)"
        by_ac[ac].append(r)

    by_priority = Counter(r.get("priority", "").strip() or "(none)" for r in rows)
    by_type = Counter(r.get("test_type", "").strip() or "(none)" for r in rows)

    cases_written = sum(1 for r in rows
                        if r.get("stage_status", "").strip() in ("case", "rtm"))
    total = len(rows)

    priority_stats = {}
    for p in ["P0", "P1", "P2", "P3"]:
        p_total = sum(1 for r in rows if r.get("priority", "").strip() == p)
        p_cases = sum(1 for r in rows
                      if r.get("priority", "").strip() == p
                      and r.get("stage_status", "").strip() in ("case", "rtm"))
        priority_stats[p] = (p_total, p_cases)

    gaps = [r for r in rows
            if r.get("stage_status", "").strip()
            not in ("case", "rtm")]

    lines = []
    lines.append("# Requirement Traceability Matrix — auto-generated\n")
    lines.append("> Generated by `qa_status.py rtm <project>/`.")
    lines.append("> Do not edit by hand. Rerun the command to refresh it.\n")

    lines.append("## Traceability Matrix\n")
    for ac in sorted(by_ac.keys()):
        lines.append(f"### {ac}\n")
        goals_in_ac = defaultdict(list)
        for r in by_ac[ac]:
            gid = r.get("goal_id", "").strip() or "?"
            goals_in_ac[gid].append(r)
        for gid in sorted(goals_in_ac.keys()):
            lines.append(f"**{gid}**\n")
            lines.append("| scenario_id | case_id | priority | test_type | stage_status |")
            lines.append("|-------------|---------|----------|-----------|--------------|")
            for r in sorted(goals_in_ac[gid],
                            key=lambda x: x.get("scenario_id", "")):
                sid = r.get("scenario_id", "")
                cid = r.get("case_id", "") or "—"
                pri = r.get("priority", "")
                tt = r.get("test_type", "")
                ss = r.get("stage_status", "")
                marker = " ⚠" if ss not in ("case", "rtm") else ""
                lines.append(f"| {sid} | {cid} | {pri} | {tt} | {ss}{marker} |")
            lines.append("")

    declared_goals = read_goal_ids(project_dir)
    goals_with_rows = {r.get("goal_id", "").strip() for r in rows}
    orphan_goals = [g for g in declared_goals if g not in goals_with_rows]
    all_goals = sorted(set(declared_goals) | (goals_with_rows - {""}),
                       key=lambda g: int(g[1:]) if g[1:].isdigit() else 0)

    lines.append("## Coverage Summary\n")
    lines.append(f"Goals: {len(all_goals)} · Scenarios: {total} · Cases written: {cases_written}\n")
    lines.append("| Priority | Scenarios | Cases Written | Coverage |")
    lines.append("|----------|-----------|---------------|----------|")
    for p in ["P0", "P1", "P2", "P3"]:
        pt, pc = priority_stats.get(p, (0, 0))
        pct = f"{pc/pt*100:.0f}%" if pt else "—"
        lines.append(f"| {p} | {pt} | {pc} | {pct} |")
    pct_all = f"{cases_written/total*100:.0f}%" if total else "—"
    lines.append(f"| **Total** | **{total}** | **{cases_written}** | **{pct_all}** |")

    lines.append("\n## Gap Analysis\n")
    if gaps:
        lines.append(f"{len(gaps)} scenario(s) without a completed test case:\n")
        lines.append("| scenario_id | goal_id | priority | stage_status |")
        lines.append("|-------------|---------|----------|--------------|")
        for r in sorted(gaps, key=lambda x: (x.get("priority", ""), x.get("scenario_id", ""))):
            lines.append(f"| {r.get('scenario_id','')} | {r.get('goal_id','')} "
                         f"| {r.get('priority','')} | {r.get('stage_status','')} |")
    else:
        lines.append("Every scenario has a completed test case.")

    lines.append("\n### Goals without any scenario\n")
    if orphan_goals:
        lines.append(f"{len(orphan_goals)} goal(s) in `02-test-goals/test-goals.md` have no scenario. "
                     "This is a coverage hole to fix before sign-off:\n")
        for g in orphan_goals:
            lines.append(f"- {g}")
    elif declared_goals:
        lines.append("None. Every declared goal has at least one scenario.")
    else:
        lines.append("Not checked: `02-test-goals/test-goals.md` is missing or declares no `## G<n>` goals.")

    lines.append("\n## Test Type Distribution\n")
    lines.append("| test_type | Count | % |")
    lines.append("|-----------|-------|---|")
    for tt in ["functional", "API", "E2E", "performance", "security", "usability"]:
        cnt = by_type.get(tt, 0)
        pct = f"{cnt/total*100:.0f}%" if total else "—"
        lines.append(f"| {tt} | {cnt} | {pct} |")
    other = sum(v for k, v in by_type.items()
                if k not in ("functional", "API", "E2E", "performance",
                             "security", "usability"))
    if other:
        lines.append(f"| (other) | {other} | {other/total*100:.0f}% |")

    rtm_dir = os.path.join(project_dir, "07-rtm")
    os.makedirs(rtm_dir, exist_ok=True)
    rtm_path = os.path.join(rtm_dir, "rtm.md")
    with open(rtm_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    print(f"RTM generated: {rtm_path}")
    print(f"  {total} scenarios, {cases_written} cases ({pct_all} coverage)")
    if gaps:
        print(f"  {len(gaps)} scenario gap(s), see Gap Analysis")
    if orphan_goals:
        print(f"  {len(orphan_goals)} goal gap(s) with no scenario: {', '.join(orphan_goals)}")
    if not gaps and not orphan_goals:
        print("  no gaps")
    return 0


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2

    if sys.argv[1] == "rtm":
        if len(sys.argv) != 3:
            print("usage: qa_status.py rtm <project-dir>/")
            return 2
        return generate_rtm(sys.argv[2])

    return status(sys.argv[1])


if __name__ == "__main__":
    sys.exit(main())
